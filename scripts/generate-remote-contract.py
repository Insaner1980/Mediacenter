ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / 'protocol/remote/v1/schema.json'


def snake(value):
    return 'r#type' if value == 'type' else re.sub(r'(?<!^)(?=[A-Z])', '_', value).lower()


def rust(schema):
    result = ['// Generated by scripts/generate-remote-contract.py; edit schema.json.',
              'use super::protocol::*;', 'use serde::{Deserialize, Serialize};', '']
    for name, definition in schema['$defs'].items():
        if 'x-tag' in definition:
            tag = definition['x-tag']
            result += ['#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]', f'#[serde(tag = "{tag}")]', f'pub enum {name} {{']
            for case in definition['oneOf']:
                value = case['properties'][tag]['const']
                variant = ''.join(part[:1].upper() + part[1:] for part in re.split(r'[_.]', value))
                result += [f'    #[serde(rename = "{value}")]', f'    {variant} {{']
                for field, rule in case['properties'].items():
                    if field != tag:
                        typ = rule['$ref'].split('/')[-1]
                        if typ == 'ConfirmationPreview': typ = f'Box<{typ}>'
                        if field not in case['required']:
                            result += ['        #[serde(default, skip_serializing_if = "Option::is_none")]']
                            typ = f'Option<{typ}>'
                        result += [f'        #[serde(rename = "{field}")]', f'        {snake(field)}: {typ},']
                result += ['    },']
            result += ['}', '']
        elif 'enum' in definition:
            result += ['#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]', f'pub enum {name} {{']
            for value in definition['enum']:
                variant = ''.join(part[:1].upper() + part[1:] for part in re.split(r'[_.]', value))
                result += [f'    #[serde(rename = "{value}")]', f'    {variant},']
            result += ['}', '']
        elif definition.get('type') == 'array' and name not in ('IdBatch', 'MediaKinds', 'ScopeSet', 'QrRows'):
            item = definition['items']['$ref'].split('/')[-1]
            result += [f"pub type {name} = BoundedList<{item}, {definition.get('minItems', 0)}, {definition['maxItems']}, false>;", '']
        elif definition.get('type') == 'object':
            stale_preview = definition.get('x-validation') == 'confirmation_stale_preview'
            derives = 'Clone, Debug, PartialEq, Deserialize' if stale_preview else 'Clone, Debug, PartialEq, Serialize, Deserialize'
            result += [f'#[derive({derives})]', '#[serde(rename_all = "camelCase")]']
            if stale_preview:
                result += [f'#[serde(try_from = "{name}Wire")]']
            result += [f'pub struct {name} {{']
            fields = []
            for field, rule in definition['properties'].items():
                typename = rule['$ref'].split('/')[-1]
                if stale_preview and typename == 'ConfirmationPreview':
                    typename = f'Box<{typename}>'
                if field not in definition['required']:
                    fields += ['    #[serde(default, skip_serializing_if = "Option::is_none")]']
                    typename = f'Option<{typename}>'
                fields += [f'    pub {snake(field)}: {typename},']
            result += fields
            result += ['}', '']
            if stale_preview:
                result += ['#[derive(Serialize, Deserialize)]', '#[serde(rename_all = "camelCase")]', f'struct {name}Wire {{']
                result += [line.replace('    pub ', '    ') for line in fields]
                result += ['}', f'impl TryFrom<{name}Wire> for {name} {{', "    type Error = &'static str;", f'    fn try_from(value: {name}Wire) -> Result<Self, Self::Error> {{',
                           '        if value.code == WireErrorCode::ConfirmationStale && value.replacement_preview.is_none() { return Err("confirmation_stale requires a replacement preview"); }', '        Ok(Self {']
                result += [f'            {snake(field)}: value.{snake(field)},' for field in definition['properties']]
                result += ['        })', '    }', '}', f'impl Serialize for {name} {{', '    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {',
                           '        if self.code == WireErrorCode::ConfirmationStale && self.replacement_preview.is_none() { return Err(serde::ser::Error::custom("confirmation_stale requires a replacement preview")); }', f'        {name}Wire {{']
                for field, rule in definition['properties'].items():
                    suffix = '' if rule['$ref'].endswith('/Bool') else '.clone()'
                    result += [f'            {snake(field)}: self.{snake(field)}{suffix},']
                result += ['        }.serialize(serializer)', '    }', '}', '']
    result += ['#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]', '#[serde(tag = "method", content = "params")]', 'pub enum RemoteCommand {']
    for method in schema['x-methods']:
        result += [f'    #[serde(rename = "{method["name"]}")]', f'    {method["type"]}({method["params"]}),']
    result += ['}', 'impl RemoteCommand {']
    for fn, typ, field in [('method', "&'static str", 'name'), ('scope', 'Scope', 'scope'), ('delivery', 'Delivery', 'delivery')]:
        result += [f'    pub fn {fn}(&self) -> {typ} {{', '        match self {']
        for m in schema['x-methods']:
            val = '"'+m[field]+'"' if field == 'name' else typ+'::'+''.join(p.capitalize() for p in m[field].split('_'))
            result += [f'            Self::{m["type"]}(..) => {val},']
        result += ['        }', '    }']
    result += ['    pub fn validate(&self, expected: Option<&Expected>) -> Result<(), RemoteError> {', '        match self {']
    for m in schema['x-methods']:
        rule = m.get('rule')
        binding = 'params' if rule else '_'
        result += [f'            Self::{m["type"]}({binding}) => {{']
        if m['expected']:
            result += ['                let expected = expected.ok_or_else(RemoteError::invalid)?;']
            for field in m['expected']:
                result += [f'                expected.{snake(field)}.as_ref().ok_or_else(RemoteError::invalid)?;']
        if rule == 'session':
            result += ['                if expected.session_id.as_ref() != Some(&params.session_id) { return Err(RemoteError::invalid()); }']
        if rule == 'lookup':
            result += ['                if params.request_id.is_some() == params.operation_id.is_some() { return Err(RemoteError::invalid()); }']
        if rule == 'device_confirmation':
            result += ['                if params.device_id.is_some() == params.confirmation_id.is_some() { return Err(RemoteError::invalid()); }']
        if rule == 'browser_confirmation':
            result += ['                if !matches!((&params.service_id, &params.profile_id, &params.confirmation_id), (Some(_), Some(_), None) | (None, None, Some(_))) { return Err(RemoteError::invalid()); }']
        if rule == 'playlist_save':
            result += ['                match params {',
                       '                    PlaylistsSaveParams::SaveQueue { playlist_id, .. } => {',
                       '                        expected.queue_revision.as_ref().ok_or_else(RemoteError::invalid)?;',
                       '                        if playlist_id.is_some() { expected.playlist_revision.as_ref().ok_or_else(RemoteError::invalid)?; }',
                       '                    }',
                       '                    _ => { expected.playlist_revision.as_ref().ok_or_else(RemoteError::invalid)?; }',
                       '                }']
        result += ['            }']
    result += ['        }', '        Ok(())', '    }', '}', '']
    result += ['#[derive(Clone, Debug, PartialEq, Serialize)]', '#[serde(untagged)]', 'pub enum RemoteResult {']
    for m in schema['x-methods']:
        result += [f'    {m["type"]}(Box<{m["result"]}>),']
    result += ['}', 'pub fn parse_reply(method: MethodName, input: &str) -> Result<RemoteReply<RemoteResult>, RemoteError> {', '    let header = validate_document(input, 262144)?;', '    if header.get("v").and_then(|v| v.as_u64()) != Some(1) { return Err(RemoteError::new(ErrorCode::VersionMismatch, "Incompatible remote protocol version.")); }', '    match method {']
    for m in schema['x-methods']:
        result += [f'        MethodName::{m["type"]} => serde_json::from_str::<RemoteReply<{m["result"]}>>(input).map(|r| r.map_result(|v| RemoteResult::{m["type"]}(Box::new(v)))).map_err(|_| RemoteError::invalid()),']
    result += ['    }', '}', '']
    return '\n'.join(result)


def kotlin(schema):
    definitions = schema['$defs']
    methods = schema['x-methods']
    header = '// Generated by Mediacenter scripts/generate-remote-contract.py; edit schema.json.\npackage com.emmah.colordock.remote.mediacenter.protocol\n\n'
    def typename(name):
        definition = definitions[name]
        if 'x-tag' in definition or 'enum' in definition or definition['type'] in ('object', 'array'):
            return name
        return {'string':'String','boolean':'Boolean','integer':'Long' if name == 'TimestampMs' else 'Int','number':'Double'}[definition['type']]
    def variant(value):
        return re.sub(r'([a-z])([A-Z])', r'\1_\2', value).replace('.', '_').upper()
    lines = [header]
    for name, definition in definitions.items():
        if 'x-tag' in definition:
            tag = definition['x-tag']
            lines += [f'sealed interface {name} {{']
            for case in definition['oneOf']:
                value = case['properties'][tag]['const']
                case_name = ''.join(p[:1].upper()+p[1:] for p in re.split(r'[_.]', value))
                fields = [f'val {k}: '+('com.emmah.colordock.remote.mediacenter.protocol.' if typename(v["$ref"].split("/")[-1]) == case_name else '')+f'{typename(v["$ref"].split("/")[-1])}'+('' if k in case['required'] else '? = null') for k,v in case['properties'].items() if k != tag]
                lines += [f'    data class {case_name}('+', '.join(fields)+f') : {name}'+ (' { override fun toString(): String = "PairingPreparation([redacted])" }' if name == 'PairingPreparation' else '')]
            lines += ['}', '']
        elif 'enum' in definition:
            lines += [f'enum class {name}(val wire: String) {{']
            lines += [f'    {variant(value)}("{value}"),' for value in definition['enum']]
            lines += ['}', '']
        elif definition['type'] == 'array':
            lines += [f'typealias {name} = List<{typename(definition["items"]["$ref"].split("/")[-1])}>', '']
        elif definition['type'] == 'object':
            if not definition['properties']:
                lines += [f'data object {name}', '']
                continue
            lines += [f'data class {name}(']
            for field, rule in definition['properties'].items():
                typ = typename(rule['$ref'].split('/')[-1])
                suffix = '' if field in definition['required'] else '? = null'
                lines += [f'    val {field}: {typ}{suffix},']
            lines += [') {', f'    override fun toString(): String = "{name}([redacted])"', '}', '']
    lines += ['enum class Delivery { READ, DURABLE, TRANSIENT }', '', 'sealed interface RemoteCommand {', '    val method: MethodName', '    val scope: Scope', '    val delivery: Delivery']
    for m in methods:
        lines += [f'    data class {m["type"]}(val params: {m["params"]}) : RemoteCommand {{',
                  f'        override val method = MethodName.{variant(m["name"])}',
                  f'        override val scope = Scope.{variant(m["scope"])}',
                  f'        override val delivery = Delivery.{m["delivery"].upper()}', '    }']
    lines += ['}', '', 'data class McRequest(val id: String, val command: RemoteCommand, val expected: Expected? = null)', '']
    lines += ['sealed interface McResult<out T> {', '    data class Success<T>(val value: T) : McResult<T>', '    data class Failure(val error: McError) : McResult<Nothing>', '}', 'typealias McError = ErrorPayload', '', 'sealed interface McReply {', '    val id: String', '    data class Success(override val id: String, val result: RemoteResult) : McReply', '    data class Failure(override val id: String, val error: McError) : McReply', '}', '', 'sealed interface RemoteResult {']
    for m in methods:
        result_type = ('com.emmah.colordock.remote.mediacenter.protocol.' if m['type'] == m['result'] else '')+m['result']
        lines += [f'    data class {m["type"]}(val value: {result_type}) : RemoteResult']
    lines += ['}', '']
    messages = '\n'.join(lines)
    lines = [header.replace('package ', '// Mechanical schema-generated allowlists: structural count metrics are reviewed in the generator.\n@file:Suppress("LongMethod", "LargeClass", "CyclomaticComplexMethod", "TooManyFunctions", "MagicNumber")\npackage ', 1), 'import org.json.JSONArray', 'import org.json.JSONException', 'import org.json.JSONObject', 'import org.json.JSONTokener', '',
             'class McProtocolException(val code: WireErrorCode) : IllegalArgumentException(code.wire)', '',
             'object RemoteJson {',
             '    private fun invalid(): Nothing = throw McProtocolException(WireErrorCode.INVALID_REQUEST)',
             '    private fun unsupported(): Nothing = throw McProtocolException(WireErrorCode.UNSUPPORTED)',
             '    private fun check(value: Boolean) { if (!value) invalid() }',
             '    private fun string(value: Any): String = value as? String ?: invalid()',
             '    private fun obj(value: Any): JSONObject = value as? JSONObject ?: invalid()',
             '    private fun number(value: Any): Double {',
             '        check(value is Number)', '        val result = (value as Number).toDouble()', '        check(result.isFinite())', '        return result', '    }',
             '    private fun integer(value: Any): Long {', '        check(value is Int || value is Long)', '        return (value as Number).toLong()', '    }',
             '    private fun document(input: String, limit: Int): JSONObject {',
             '        check(input.toByteArray(Charsets.UTF_8).size <= limit)',
             '        StrictJson.validate(input)', '        val tokenizer = JSONTokener(input)', '        val result = obj(tokenizer.nextValue())', "        check(tokenizer.nextClean() == '\\u0000')", '        return result', '    }',
             '    private inline fun <T> safely(block: () -> T): T = try { block() } catch (_: JSONException) { invalid() }', '',
             '    fun parseRequest(input: String): McRequest = safely {',
             '        val root = document(input, 65536)',
             '        if (root.opt("v") != 1) throw McProtocolException(WireErrorCode.VERSION_MISMATCH)',
             '        val id = readId(root.get("id"))',
             '        val expected = if (root.isNull("expected")) null else readExpected(root.get("expected"))',
             '        val params = root.get("params")', '        val command = when (readMethodName(root.get("method"))) {']
    for m in methods:
        lines += [f'            MethodName.{variant(m["name"])} -> RemoteCommand.{m["type"]}(read{m["params"]}(params))']
    lines += ['        }', '        val request = McRequest(id, command, expected)', '        validate(request)', '        request', '    }', '',
              '    fun encodeRequest(request: McRequest): String {',
              '        val result = JSONObject().put("v", 1).put("id", request.id).put("method", request.command.method.wire)',
              '        request.expected?.let { result.put("expected", writeExpected(it)) }',
              '        result.put("params", when (val command = request.command) {']
    for m in methods:
        lines += [f'            is RemoteCommand.{m["type"]} -> write{m["params"]}(command.params)']
    lines += ['        })', '        val encoded = result.toString()', '        parseRequest(encoded)', '        return encoded', '    }', '',
              '    fun parseHello(input: String): Hello = safely { readHello(document(input, 262144)) }',
              '    fun parseSnapshot(input: String): RemoteSnapshot = safely { readRemoteSnapshot(document(input, 262144)) }', '',
              '    fun parseReply(method: MethodName, input: String): McReply = safely {',
              '        val root = document(input, 262144)',
              '        if (root.opt("v") != 1) throw McProtocolException(WireErrorCode.VERSION_MISMATCH)',
              '        val id = readId(root.get("id"))',
              '        val ok = readBool(root.get("ok"))',
              '        check(if (ok) root.has("result") && !root.has("error") else root.has("error") && !root.has("result"))',
              '        if (!ok) return@safely McReply.Failure(id, readErrorPayload(root.get("error")))',
              '        val result = root.get("result")',
              '        McReply.Success(id, when (method) {']
    for m in methods:
        lines += [f'            MethodName.{variant(m["name"])} -> RemoteResult.{m["type"]}(read{m["result"]}(result))']
    lines += ['        })', '    }', '', '    fun encodeReply(reply: McReply): String {',
              '        val root = JSONObject().put("v", 1).put("id", reply.id)',
              '        when (reply) {',
              '            is McReply.Failure -> root.put("ok", false).put("error", writeErrorPayload(reply.error))',
              '            is McReply.Success -> {', '                root.put("ok", true).put("result", when (val result = reply.result) {']
    for m in methods:
        lines += [f'                is RemoteResult.{m["type"]} -> write{m["result"]}(result.value)']
    lines += ['            })', '            }', '        }', '        return root.toString()', '    }', '',
              '    private fun validate(request: McRequest) {', '        val expected = request.expected', '        when (val command = request.command) {']
    for m in methods:
        lines += [f'            is RemoteCommand.{m["type"]} -> {{']
        for field in m['expected']:
            lines += [f'                check(expected?.{field} != null)']
        rule = m.get('rule')
        if rule == 'session':lines += ['                check(expected?.sessionId == command.params.sessionId)']
        if rule == 'lookup':lines += ['                check((command.params.requestId != null) != (command.params.operationId != null))']
        if rule == 'device_confirmation':lines += ['                check((command.params.deviceId != null) != (command.params.confirmationId != null))']
        if rule == 'browser_confirmation':lines += ['                check(if (command.params.confirmationId != null) { command.params.serviceId == null && command.params.profileId == null } else { command.params.serviceId != null && command.params.profileId != null })']
        if rule == 'playlist_save':lines += ['                when (val params = command.params) {', '                    is PlaylistsSaveParams.SaveQueue -> {', '                        check(expected?.queueRevision != null)', '                        check(params.playlistId == null || expected?.playlistRevision != null)', '                    }', '                    else -> check(expected?.playlistRevision != null)', '                }']
        lines += ['            }']
    lines += ['        }', '    }', '']
    for name, definition in definitions.items():
        typ = typename(name)
        lines += [f'    private fun read{name}(value: Any): {typ} {{']
        if 'x-tag' in definition:
            tag = definition['x-tag']
            lines += ['        val source = obj(value)', f'        return when (string(source.get("{tag}"))) {{']
            for case in definition['oneOf']:
                value = case['properties'][tag]['const']
                case_name = ''.join(p[:1].upper()+p[1:] for p in re.split(r'[_.]', value))
                args = []
                for k,v in case['properties'].items():
                    if k == tag: continue
                    expr = f'read{v["$ref"].split("/")[-1]}(source.get("{k}"))'
                    if k not in case['required']: expr = f'if (source.isNull("{k}")) {{\n null\n }} else {{\n {expr}\n }}'
                    args.append(f'{k} = {expr}')
                lines += [f'            "{value}" -> {name}.{case_name}('+', '.join(args)+')']
            lines += ['            else -> unsupported()', '        }']
        elif 'enum' in definition:
            lines += [f'        return {name}.entries.firstOrNull {{ it.wire == string(value) }} ?: unsupported()']
        elif definition['type'] == 'object':
            lines += ['        val source = obj(value)']
            if not definition['properties']:
                lines[-1] = '        obj(value)'
                lines += [f'        return {name}']
            else:
                stale_preview = definition.get('x-validation') == 'confirmation_stale_preview'
                lines += [f'        '+('val result = ' if stale_preview else 'return ')+f'{name}(']
                for field, rule in definition['properties'].items():
                    subtype = rule['$ref'].split('/')[-1]
                    expr = f'read{subtype}(source.get("{field}"))'
                    if field not in definition['required']:expr = f'if (source.isNull("{field}")) {{\n null\n }} else {{\n {expr}\n }}'
